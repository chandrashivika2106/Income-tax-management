-- ============================================================
-- INCOME TAX MANAGEMENT SYSTEM
-- Database: Oracle Database 21c XE
-- Schema: TAXAPP
-- ============================================================

-- TABLE 1: USERS
-- Stores login credentials.

CREATE TABLE USERS (
USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
USERNAME VARCHAR2(50) NOT NULL,
PASSWORD_HASH VARCHAR2(255) NOT NULL,
CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
CONSTRAINT UQ_USERS_USERNAME UNIQUE (USERNAME)
);

-- TABLE 2: TAXPAYERS
-- Stores taxpayer information.

CREATE TABLE TAXPAYERS (
TAXPAYER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
USER_ID NUMBER NOT NULL,
FULL_NAME VARCHAR2(100) NOT NULL,
PAN VARCHAR2(10) NOT NULL,
FINANCIAL_YEAR VARCHAR2(9) NOT NULL,

```
CONSTRAINT PK_TAXPAYERS PRIMARY KEY (TAXPAYER_ID),
CONSTRAINT UQ_TAXPAYERS_PAN UNIQUE (PAN),
CONSTRAINT FK_TAXPAYER_USER
    FOREIGN KEY (USER_ID)
    REFERENCES USERS(USER_ID)
```

);

-- TABLE 3: INCOME_DETAILS
-- Stores income, deductions and TDS information.

CREATE TABLE INCOME_DETAILS (
INCOME_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
TAXPAYER_ID NUMBER NOT NULL,
SALARY_INCOME NUMBER(12,2) DEFAULT 0 NOT NULL,
HOUSE_PROPERTY_INCOME NUMBER(12,2) DEFAULT 0 NOT NULL,
OTHER_INCOME NUMBER(12,2) DEFAULT 0 NOT NULL,
ELIGIBLE_DEDUCTIONS NUMBER(12,2) DEFAULT 0 NOT NULL,
TDS_AMOUNT NUMBER(12,2) DEFAULT 0 NOT NULL,

```
CONSTRAINT PK_INCOME_DETAILS PRIMARY KEY (INCOME_ID),

CONSTRAINT FK_INCOME_TAXPAYER
    FOREIGN KEY (TAXPAYER_ID)
    REFERENCES TAXPAYERS(TAXPAYER_ID),

CONSTRAINT CHK_SALARY
    CHECK (SALARY_INCOME >= 0),

CONSTRAINT CHK_HOUSE_INCOME
    CHECK (HOUSE_PROPERTY_INCOME >= 0),

CONSTRAINT CHK_OTHER_INCOME
    CHECK (OTHER_INCOME >= 0),

CONSTRAINT CHK_DEDUCTIONS
    CHECK (ELIGIBLE_DEDUCTIONS >= 0),

CONSTRAINT CHK_TDS
    CHECK (TDS_AMOUNT >= 0)
```

);

-- TABLE 4: TAX_RECORDS
-- Stores calculated tax summaries.

CREATE TABLE TAX_RECORDS (
RECORD_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
TAXPAYER_ID NUMBER NOT NULL,
GROSS_TOTAL_INCOME NUMBER(12,2) NOT NULL,
TAXABLE_INCOME NUMBER(12,2) NOT NULL,
INCOME_TAX NUMBER(12,2) NOT NULL,
CESS NUMBER(12,2) NOT NULL,
TOTAL_TAX_LIABILITY NUMBER(12,2) NOT NULL,
TAX_PAYABLE NUMBER(12,2) NOT NULL,
CALCULATION_DATE DATE DEFAULT SYSDATE NOT NULL,

```
CONSTRAINT PK_TAX_RECORDS PRIMARY KEY (RECORD_ID),

CONSTRAINT FK_RECORD_TAXPAYER
    FOREIGN KEY (TAXPAYER_ID)
    REFERENCES TAXPAYERS(TAXPAYER_ID),

CONSTRAINT CHK_GROSS_INCOME
    CHECK (GROSS_TOTAL_INCOME >= 0),

CONSTRAINT CHK_TAXABLE_INCOME
    CHECK (TAXABLE_INCOME >= 0),

CONSTRAINT CHK_INCOME_TAX
    CHECK (INCOME_TAX >= 0),

CONSTRAINT CHK_CESS
    CHECK (CESS >= 0),

CONSTRAINT CHK_TOTAL_TAX
    CHECK (TOTAL_TAX_LIABILITY >= 0),

CONSTRAINT CHK_TAX_PAYABLE
    CHECK (TAX_PAYABLE >= 0)
```

);

-- ============================================================
-- VERIFY TABLE CREATION
-- ============================================================

SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
'USERS',
'TAXPAYERS',
'INCOME_DETAILS',
'TAX_RECORDS'
)
ORDER BY TABLE_NAME;

